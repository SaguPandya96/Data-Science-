"""Evaluator alignment: do the automated checks agree with human judgement?"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import streamlit as st

sys.path.insert(0, str(Path(__file__).parent.parent))

import data_access as data

st.set_page_config(page_title="Evaluator alignment", page_icon="🤝", layout="wide")


def main() -> None:
    """Render the alignment page."""
    st.title("Evaluator alignment")
    st.caption(
        "Human-versus-human agreement is the ceiling. No automated evaluator should be "
        "expected to agree with humans more than humans agree with each other."
    )

    options = data.run_options()
    if not options:
        st.warning("No runs stored. Run `evalforge demo` first.")
        st.stop()

    label = st.sidebar.selectbox("Select a run", list(options), key="align_run")
    run_id = options[label]

    report = data.alignment_for(run_id)
    if report is None:
        st.info(
            "No blind annotations exist for this run yet, so evaluator alignment is "
            "unverified.\n\n"
            "Collect them with:\n\n```bash\nevalforge annotate\n```\n\n"
            "Or generate clearly-labelled synthetic annotations for demonstration:\n\n"
            "```bash\npython scripts/simulate_annotations.py\n```"
        )
        st.stop()

    synthetic = data.synthetic_annotation_count(run_id)
    if synthetic:
        st.error(
            f"**{synthetic} of the annotations backing this page are synthetic**, "
            "generated by `scripts/simulate_annotations.py` so the analysis pipeline is "
            "demonstrable offline. They are *not* human judgements. Every statistic below "
            "describes the simulator, not human agreement, and must not be cited as "
            "evidence that the evaluators match human raters."
        )

    columns = st.columns(4)
    columns[0].metric("Annotations", report.annotation_count)
    columns[1].metric("Annotators", report.annotator_count)
    columns[2].metric("Doubly annotated", report.doubly_annotated)
    ceiling = report.statistic("cohens_kappa", "annotator_a", "annotator_b")
    columns[3].metric(
        "Human-human kappa",
        f"{ceiling.value:.3f}" if ceiling else "n/a",
        help="The ceiling for automated agreement." if ceiling else None,
    )

    st.divider()
    st.subheader("Agreement statistics")

    if report.statistics:
        frame = pd.DataFrame(
            [
                {
                    "statistic": item.name,
                    "rater A": item.rater_a,
                    "rater B": item.rater_b,
                    "dimension": item.dimension or "overall",
                    "value": item.value,
                    "n": item.n,
                    "reading": item.interpretation,
                }
                for item in report.statistics
            ]
        )
        st.dataframe(frame.style.format({"value": "{:.4f}"}), width="stretch", hide_index=True)
        st.caption(
            "Cohen's kappa corrects for chance agreement — with an 85% pass rate, two "
            "raters who always say 'pass' show 85% raw agreement and kappa near zero. "
            "Weighted kappa is used for ordinal rubric ratings, where a 4-vs-5 "
            "disagreement is not the same as 1-vs-5. Spearman is used for score "
            "correlation because rubric ratings are ordinal, not interval."
        )

    st.divider()
    st.subheader("Confusion matrices")
    if report.confusion_matrices:
        for name, matrix in report.confusion_matrices.items():
            st.markdown(f"**{name.replace('_', ' ')}**")
            frame = pd.DataFrame(
                [
                    {
                        "": "A passed",
                        "B passed": matrix["true_pass"],
                        "B failed": matrix["false_fail"],
                    },
                    {
                        "": "A failed",
                        "B passed": matrix["false_pass"],
                        "B failed": matrix["true_fail"],
                    },
                ]
            )
            st.dataframe(frame, width="stretch", hide_index=True)
        st.caption(
            "'A failed / B passed' is the dangerous cell when B is automated: a false "
            "pass ships a broken agent."
        )

    st.divider()
    left, right = st.columns(2)
    with left:
        st.subheader("Agreement by conversation length")
        if report.agreement_by_length:
            frame = pd.DataFrame(
                {
                    "turns": [int(k) for k in report.agreement_by_length],
                    "agreement": list(report.agreement_by_length.values()),
                }
            ).sort_values("turns")
            st.line_chart(frame.set_index("turns")["agreement"], height=280)
            st.caption("Tests whether evaluator reliability decays as context length grows.")
    with right:
        st.subheader("Agreement by category")
        if report.agreement_by_failure_type:
            st.bar_chart(report.agreement_by_failure_type, horizontal=True, height=280)

    st.divider()
    st.subheader("Bias analysis")
    if report.bias_findings:
        for finding in report.bias_findings:
            with st.expander(f"{finding['bias'].replace('_', ' ').title()}", expanded=False):
                st.write({k: v for k, v in finding.items() if k != "interpretation"})
                st.caption(finding.get("interpretation", ""))
    else:
        st.info("Not enough annotations to run the bias analyses.")

    st.divider()
    st.subheader("Disagreement examples")
    st.caption(
        "Sorted by score gap. These are the cases worth adjudicating against the trace "
        "evidence — where a human and the automated verdict diverge, one of them is wrong."
    )
    if report.disagreement_examples:
        st.dataframe(
            pd.DataFrame(report.disagreement_examples).style.format(precision=3),
            width="stretch",
            hide_index=True,
        )
    else:
        st.success("Human and automated verdicts agreed on every annotated session.")

    if report.limitations:
        st.divider()
        st.subheader("Limitations")
        for item in report.limitations:
            st.markdown(f"- {item}")


main()
